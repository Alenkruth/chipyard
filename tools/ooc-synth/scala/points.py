#!/usr/bin/env python3
"""Point registry for the OOC elaborator: module name -> instance path in the tile and the
mapping of point params onto ooc.spec keys (see src/OocPoint.scala).

  points.py resolve <module> <variant> <params> --options <options.json> [--widthmap <widthmap.json>] [--allow-off-list]
      prints one JSON object: point, module, variant, params (canonical), spec, pattern, notes
  points.py modules --options <options.json>
      prints the registry as JSON (module -> params, option lists, instance path)

Option VALUES come only from options.json (generated by ooc.DumpOptions from CoreFuzzing.scala).
Module and param names follow tools/ooc-synth/analysis/manifest.py (agent C).
"""
import json, os, sys

TILE = "element_reset_domain_boom_tile"
# module: (instance-path pattern, [(param, spec key, option list)], instances of this module per tile)
REG = {
    "FetchBuffer":      ("frontend.fb",                [("entries", "fb", "fetchBufferEntryOptions")], 1),
    "Rob":              ("core.rob",                   [("entries", "rob", "robEntryOptions")], 1),
    "FetchTargetQueue": ("frontend.ftq",               [("entries", "ftq", "ftQueueEntryOptions")], 1),
    "BoomRAS":          ("frontend.ras",               [("entries", "ras", "rasEntryCountOptions")], 1),
    "RegfileInt":       ("core.iregfile",              [("pregs", "iprf", "pregFileSizeOptions")], 1),
    "RegfileFp":        ("core.FpPipeline.fregfile",   [("pregs", "fprf", "fpPregFileSizeOptions")], 1),
    "FreelistInt":      ("core.rename_stage.freelist", [("pregs", "iprf", "pregFileSizeOptions")], 1),
    "FreelistFp":       ("core.fp_rename_stage.freelist", [("pregs", "fprf", "fpPregFileSizeOptions")], 1),
    "IssueInt":         ("core.int_issue_unit",        [("entries", "iq_int", "issueQueueEntryOptions")], 1),
    "IssueMem":         ("core.mem_issue_unit",        [("entries", "iq_mem", "issueQueueEntryOptions")], 1),
    "IssueFp":          ("core.FpPipeline.fp_issue_unit", [("entries", "iq_fp", "issueQueueEntryOptions")], 1),
    "Lsu":              (TILE + ".lsu",                [("ldq", "ldq", "ldQueueEntryOptions"),
                                                        ("stq", "stq", "stQueueEntryOptions")], 1),
    # the BPD has nBanks=2 identical banks (frontend.bpd.banked_predictors_{0,1}); bank 0 is synthesized
    "BTB":              ("frontend.bpd.banked_predictors_0.btb", [("sets", "btb_sets", "btbSetOptions"),
                                                                  ("ways", "btb_ways", "btbWayOptions")], 2),
    "Tage":             ("frontend.bpd.banked_predictors_0.tage", [("tables", "tage", "tagetableCountOptions")], 2),
    "ICache":           ("frontend.icache",            [("sets", "ic_sets", "icacheSetOptions"),
                                                        ("ways", "ic_ways", "cacheWayOptions")], 1),
    "DCache":           (TILE + ".dcache",             [("sets", "dc_sets", "dcacheSetOptions"),
                                                        ("ways", "dc_ways", "cacheWayOptions")], 1),
    "Core":             (TILE + ".core",               [], 1),
    "Tile":             (TILE,                         [], 1),
}
# D$ replacement policy (BoomCoreParams.dcacheReplPolicy codes, parameters.scala:142-148)
# Pattern counting every copy of the module in one tile (instances_per_tile is MEASURED from the
# elaborated design with it and must equal the registry value, else the point fails).
COUNT_PATTERN = {
    "BTB": "frontend.bpd.*.btb",
    "Tage": "frontend.bpd.*.tage",
}
# What the extracted instance does and does not contain (copied into elab.json).
NOTES = {
    "BTB": "bank 0 of the 2 identical BPD banks (frontend.bpd.banked_predictors_{0,1}); tile area = 2 x this point",
    "Tage": "bank 0 of the 2 identical BPD banks (frontend.bpd.banked_predictors_{0,1}); tile area = 2 x this point",
    "Core": "BoomCore only: excludes the frontend (FetchBuffer, FTQ, BPD, RAS, ICache), the LSU, the DCache and the PTW, "
            "which are tile-level siblings; whole-tile = module Tile",
    "Lsu": "LSU only (LDQ/STQ, TLB, forwarding); the DCache is a sibling instance",
    "DCache": "BoomNonBlockingDCache incl. MSHRs, prefetcher hook, meta/data arrays; the LSU is a sibling instance",
    "ICache": "ICache incl. tag/data arrays (and ift_tag_meta when IFT is on)",
    "RegfileInt": "integer register file only; the PRF size also sizes FreelistInt, busy table and rename maps in the same config",
    "RegfileFp": "FP register file only; the PRF size also sizes FreelistFp in the same config",
    "FreelistInt": "integer rename free list only",
    "FreelistFp": "FP rename free list only",
    "IssueInt": "integer issue unit (slots + select); issue ports = issue_width.int",
    "IssueMem": "memory issue unit (slots + select); issue ports = issue_width.mem",
    "IssueFp": "FP issue unit (slots + select); issue ports = issue_width.fp",
}
# IFT-bridge state taps that pin a geometry when ENABLE_IFT_BRIDGE (variant ift / reconf_ift).
# At any other geometry these modules use variant ift_nobridge (owner decision 2026-10-28).
BRIDGE_PINS = {
    "ICache": "icache.scala:283 (64 sets x 8 ways)",
    "BTB": "btb.scala:331 (128 sets x 2 ways)",
    "Tage": "tage.scala:489 (7 tables)",
    "DCache": "dcache.scala:1775 (128 sets x 8 ways, 8 MSHRs, memWidth 2)",
    "BoomRAS": "frontend.scala:1383 (32 entries)",
}
REPL = {"plru": 0, "trulru": 1, "truelru": 1, "random": 3}
VARIANTS = ("base", "ift", "ift_nobridge", "reconf_base", "reconf_ift")


def resolve(module, variant, params, opts, allow_off_list=False, widthmap=None):
    if module not in REG:
        raise SystemExit("unknown module %r; known: %s" % (module, ", ".join(sorted(REG))))
    if variant not in VARIANTS:
        raise SystemExit("unknown variant %r; known: %s" % (variant, ", ".join(VARIANTS)))
    pattern, dims, ninst = REG[module]
    kv = {}
    for item in [x for x in params.split(",") if x.strip()]:
        if "=" not in item:
            raise SystemExit("bad param %r (want k=v)" % item)
        k, v = item.split("=", 1)
        kv[k.strip()] = v.strip()
    known = {d[0] for d in dims} | {"width", "width_mode"} | ({"repl"} if module == "DCache" else set())
    bad = set(kv) - known
    if bad:
        raise SystemExit("module %s takes params %s; got unknown %s" % (module, sorted(known), sorted(bad)))
    spec = {"variant": variant}
    canon = []
    is_max = True
    for p, key, lst in dims:
        vals = opts[lst]
        v = int(kv.get(p, max(vals)))
        if v not in vals and not allow_off_list:
            raise SystemExit("%s=%d is not in %s %s" % (p, v, lst, vals))
        is_max &= (v == max(vals))
        canon.append("%s=%d" % (p, v))
        if v != max(vals):
            spec[key] = str(v)
    if "repl" in kv:
        r = kv["repl"].lower()
        if r not in REPL:
            raise SystemExit("repl must be one of %s" % sorted(REPL))
        canon.append("repl=%s" % r)
        if REPL[r] != 0:
            spec["dc_repl"] = str(REPL[r])
            is_max = False
    widths = opts["coreWidthOptions"]
    w = int(kv.get("width", max(widths)))
    if w not in widths and not allow_off_list:
        raise SystemExit("width=%d is not in coreWidthOptions %s" % (w, widths))
    wmode = kv.get("width_mode", "full")
    if wmode not in ("full", "dispatch_only"):
        raise SystemExit("width_mode must be full or dispatch_only")
    if "width" in kv or module in ("Core", "Tile"):
        canon.append("width=%d" % w)
    if w != max(widths):
        spec["width"] = str(w)
        is_max = False
        if wmode != "full":
            # at the max width both modes are the same config, so the tag is dropped there
            canon.append("width_mode=%s" % wmode)
            spec["width_mode"] = wmode
    else:
        wmode = "full"
    # The D$ tap also pins memWidth 2 (dcache.scala:1775), and a full-width-mode core at width < 4 has
    # memWidth 1 (WidthMap), so NO module elaborates as ift/reconf_ift there (verified: Core/ift/width=2,1).
    if variant in ("ift", "reconf_ift") and w != max(widths) and wmode == "full" \
            and os.environ.get("OOC_IGNORE_PINS") != "1":
        raise SystemExit("%s/%s width=%d width_mode=full: the D$ IFT-bridge tap needs memWidth 2 (%s); use "
                         "ift_nobridge or width_mode=dispatch_only" % (module, variant, w, BRIDGE_PINS["DCache"]))
    # OOC_IGNORE_PINS=1 skips this check (only to re-prove a pin by a failing elaboration)
    if variant in ("ift", "reconf_ift") and module in BRIDGE_PINS and not is_max \
            and os.environ.get("OOC_IGNORE_PINS") != "1":
        raise SystemExit("%s/%s: the IFT-bridge state tap pins the geometry (%s); use variant ift_nobridge "
                         "at non-max points (owner decision 2026-10-28)" % (module, variant, BRIDGE_PINS[module]))
    if variant.startswith("reconf") and not is_max:
        raise SystemExit("reconf variants exist only at the max size and width (plan section 7)")
    cparams = ",".join(canon)
    sspec = ";".join("%s=%s" % (k, spec[k]) for k in ["variant"] + sorted(k for k in spec if k != "variant"))
    return {"point": "%s/%s/%s" % (module, variant, cparams), "module": module, "variant": variant,
            "params": cparams, "spec": sspec, "pattern": pattern, "instances_per_tile": ninst,
            "width": w, "width_mode": wmode,
            # any point that is not the hardware-built configuration (max sizes, max width, PLRU) is
            # elaborated with the static-clamp jar (scala/patched_jar.sh); see elaborate.sh OOC_STATIC_FIX
            "static_fix": not is_max,
            "issue_width": (widthmap[str(w)]["issue_width"] if wmode == "full" else widthmap["fuzzing_issue_width"])
                           if widthmap else None,
            "count_pattern": COUNT_PATTERN.get(module, pattern),
            "extraction_note": NOTES.get(module, "")}


def main(a):
    opts_path = a[a.index("--options") + 1] if "--options" in a else None
    if not opts_path:
        raise SystemExit("--options <options.json> is required")
    with open(opts_path) as f:
        opts = json.load(f)
    if a[1] == "resolve":
        wm = None
        if "--widthmap" in a:
            with open(a[a.index("--widthmap") + 1]) as f:
                wm = json.load(f)
        r = resolve(a[2], a[3], a[4], opts, "--allow-off-list" in a, wm)
        print(json.dumps(r, sort_keys=True))
    elif a[1] == "modules":
        out = {m: {"instance_pattern": p, "instances_per_tile": n,
                   "params": [{"param": q, "option_list": l, "values": opts[l]} for q, _, l in d]}
               for m, (p, d, n) in sorted(REG.items())}
        print(json.dumps(out, indent=1, sort_keys=True))
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
