#!/usr/bin/env python3
"""Deterministic HTML report from the aggregator outputs. No timestamps, no agent-written text.
python3 -I report.py --dir AGG_DIR [--manifest manifest.csv] --out report.html"""
import argparse, html, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *

CSS = ("body{font:14px system-ui,sans-serif;margin:16px;background:#fff;color:#111}"
       "table{border-collapse:collapse;margin:8px 0 24px}td,th{border:1px solid #bbb;padding:2px 6px;text-align:right}"
       "td.l,th.l{text-align:left}th{background:#eee}h2{margin-top:28px}"
       ".bar{display:inline-block;height:9px;background:#47a;vertical-align:middle}"
       "@media(prefers-color-scheme:dark){body{background:#161616;color:#eee}th{background:#333}td,th{border-color:#555}.bar{background:#8bd}}")


def table(header, rows, left=1, bar=None):
    o = ["<table><tr>"]
    for i, h in enumerate(header):
        o.append('<th class="%s">%s</th>' % ("l" if i < left else "", html.escape(h)))
    o.append("</tr>")
    mx = 0
    if bar is not None:
        mx = max([abs(float(r[bar])) for r in rows if str(r[bar]).lstrip("-").replace(".", "", 1).isdigit()] or [0])
    for r in rows:
        o.append("<tr>")
        for i, c in enumerate(r):
            cell = html.escape(str(c))
            if bar == i and mx:
                try:
                    cell += ' <span class="bar" style="width:%dpx"></span>' % int(100 * abs(float(c)) / mx)
                except ValueError:
                    pass
            o.append('<td class="%s">%s</td>' % ("l" if i < left else "", cell))
        o.append("</tr>")
    o.append("</table>")
    return "".join(o)


def section(title, path, left, bar_col=None, note=""):
    if not os.path.exists(path):
        return "<h2>%s</h2><p>missing</p>" % html.escape(title)
    rows = read_csv(path)
    if not rows:
        return "<h2>%s</h2><p>no rows</p>" % html.escape(title)
    hdr = list(rows[0].keys())
    b = hdr.index(bar_col) if bar_col in hdr else None
    return "<h2>%s</h2>%s%s" % (html.escape(title), "<p>%s</p>" % html.escape(note) if note else "",
                               table(hdr, [[r[h] for h in hdr] for r in rows], left, b))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True); ap.add_argument("--manifest"); ap.add_argument("--out", required=True)
    a = ap.parse_args()
    o = ['<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
         "<title>OOC synthesis report</title><style>%s</style></head><body><h1>OOC synthesis report</h1>" % CSS]
    o.append("<p>Post-synthesis, out-of-context, raw columns only. Generated by report.py from the CSV/JSON files in the aggregate directory.</p>")
    if a.manifest and os.path.exists(a.manifest):
        rows = read_csv(a.manifest)
        mods = sorted({r["module"] for r in rows})
        sts = sorted({r["status"] for r in rows})
        t = []
        for m in mods:
            t.append([m] + [sum(1 for r in rows if r["module"] == m and r["status"] == s) for s in sts] + [sum(1 for r in rows if r["module"] == m)])
        t.append(["ALL"] + [sum(1 for r in rows if r["status"] == s) for s in sts] + [len(rows)])
        o.append("<h2>Manifest status</h2>" + table(["module"] + sts + ["total"], t))
    d = a.dir
    o.append(section("Areas (raw)", os.path.join(d, "areas_raw.csv"), 4, "total_luts"))
    o.append(section("IFT overhead per module and IFT-named children", os.path.join(d, "ift_overhead.csv"), 6, "total_luts",
                     "variant_pair says where each number comes from: delta = ift_nobridge-base for BTB/Tage/ICache/DCache (in-core IFT, taps off), ift-base for all other modules; tap_bridge = ift-ift_nobridge at max size; ift_child rows are IFT-named sub-instances of the listed variant."))
    o.append(section("Reconfiguration overhead at max size", os.path.join(d, "reconf_overhead.csv"), 3, "d_total_luts"))
    o.append(section("Whole core vs sum of modules", os.path.join(d, "core_vs_sum.csv"), 6, "total_luts",
                     "residual = measured whole core minus sum of modules (glue and cross-boundary optimization), per variant, width and width_mode; sum_basis states which module widths were summed."))
    o.append("</body></html>\n")
    with open(a.out, "w") as f:
        f.write("\n".join(o))


if __name__ == "__main__":
    main()
